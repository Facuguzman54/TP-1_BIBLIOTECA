CREATE TABLE CIUDAD (
    ID_CIUDAD INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL
);

CREATE TABLE CAMPUS (
    ID_CAMPUS INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    ID_CIUDAD INT NOT NULL,
    FOREIGN KEY (ID_CIUDAD) REFERENCES CIUDAD(ID_CIUDAD)
);

CREATE TABLE CARRERA (
    ID_CARRERA INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    ID_CAMPUS INT NOT NULL,
    FOREIGN KEY (ID_CAMPUS) REFERENCES CAMPUS(ID_CAMPUS)
);

CREATE TABLE ESTUDIANTE (
    RUT_ESTUDIANTE INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    APELLIDO VARCHAR(50) NOT NULL,
    EDAD INT NOT NULL,
    TELEFONO VARCHAR(15) NOT NULL,
    DIRECCION VARCHAR(100) NOT NULL,
    ID_CARRERA INT NOT NULL,
    FOREIGN KEY (ID_CARRERA) REFERENCES CARRERA(ID_CARRERA)
);

CREATE TABLE FUNCIONARIO (
    RUT_FUNCIONARIO INT PRIMARY KEY,
    NOMBRES VARCHAR(50) NOT NULL,
    APELLIDO VARCHAR(50) NOT NULL,
    EDAD INT NOT NULL,
    DIRECCION VARCHAR(100) NOT NULL,
    SALUD VARCHAR(50) NOT NULL,
    ID_CAMPUS INT NOT NULL,
    FOREIGN KEY (ID_CAMPUS) REFERENCES CAMPUS(ID_CAMPUS)
);

CREATE TABLE AUTOR (
    RUT_AUTOR INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    APELLIDO VARCHAR(50) NOT NULL
);

CREATE TABLE EDITORIAL (
    ID_EDITORIAL INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL,
    PAIS VARCHAR(50) NOT NULL
);

CREATE TABLE TIPO (
    ID_TIPO INT PRIMARY KEY,
    TIPO_DESCRIPCION VARCHAR(50) NOT NULL
);

CREATE TABLE BIBLIOTECA (
    ID_BIBLIOTECA INT PRIMARY KEY,
    NOMBRE VARCHAR(50) NOT NULL
);

CREATE TABLE LIBRO (
    COD_LIBRO INT PRIMARY KEY,
    TITULO VARCHAR(100) NOT NULL,
    ANIO INT NOT NULL,
    ID_BIBLIOTECA INT NOT NULL,
    ID_TIPO INT NOT NULL,
    RUT_AUTOR INT NOT NULL,
    ID_EDITORIAL INT NOT NULL,
    FOREIGN KEY (ID_BIBLIOTECA) REFERENCES BIBLIOTECA(ID_BIBLIOTECA),
    FOREIGN KEY (ID_TIPO) REFERENCES TIPO(ID_TIPO),
    FOREIGN KEY (RUT_AUTOR) REFERENCES AUTOR(RUT_AUTOR),
    FOREIGN KEY (ID_EDITORIAL) REFERENCES EDITORIAL(ID_EDITORIAL)
);

CREATE TABLE PRESTAMO (
    RUT_ESTUDIANTE INT NOT NULL,
    RUT_FUNCIONARIO INT NOT NULL,
    COD_LIBRO INT NOT NULL,
    FECHA_PRESTAMO DATE NOT NULL,
    FECHA_ENTREGA DATE NOT NULL,
    PRIMARY KEY (RUT_ESTUDIANTE, RUT_FUNCIONARIO, COD_LIBRO),
    FOREIGN KEY (RUT_ESTUDIANTE) REFERENCES ESTUDIANTE(RUT_ESTUDIANTE),
    FOREIGN KEY (RUT_FUNCIONARIO) REFERENCES FUNCIONARIO(RUT_FUNCIONARIO),
    FOREIGN KEY (COD_LIBRO) REFERENCES LIBRO(COD_LIBRO)
);

CREATE TABLE AUDITORIA_PRESTAMO (
    ID_AUDITORIA INT AUTO_INCREMENT PRIMARY KEY,
    RUT_EST INT NOT NULL,
    COD_LIBRO INT NOT NULL,
    FECHA_REGISTRO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ACCION VARCHAR(50) NOT NULL,
    FOREIGN KEY (RUT_EST) REFERENCES ESTUDIANTE(RUT_ESTUDIANTE),
    FOREIGN KEY (COD_LIBRO) REFERENCES LIBRO(COD_LIBRO)
);